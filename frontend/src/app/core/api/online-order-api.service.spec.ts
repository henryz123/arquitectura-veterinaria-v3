import '@angular/compiler';
import { provideHttpClient } from '@angular/common/http';
import { HttpTestingController, provideHttpClientTesting } from '@angular/common/http/testing';
import { TestBed } from '@angular/core/testing';
import { describe, expect, it } from 'vitest';
import { OnlineOrderApiService } from './online-order-api.service';

describe('OnlineOrderApiService', () => {
  it('uses the authenticated B05-B endpoints with the expected methods and payloads', () => {
    TestBed.configureTestingModule({ providers: [provideHttpClient(), provideHttpClientTesting()] });
    const service = TestBed.inject(OnlineOrderApiService);
    const http = TestBed.inject(HttpTestingController);
    const order = { operationId: '00000000-0000-4000-8000-000000000001', deliveryMode: 'RECOJO' as const, coordinationPhone: '999 000 111', deliveryAddress: null, expectedDeliveryFeePen: null, lines: [{ productId: '00000000-0000-4000-8000-000000000002', quantity: 1, expectedUnitPricePen: 14.5 }] };

    service.checkoutOptions().subscribe();
    expect(http.expectOne('/api/v1/online-orders/checkout-options').request.method).toBe('GET');
    service.create(order).subscribe();
    const created = http.expectOne('/api/v1/online-orders');
    expect(created.request.method).toBe('POST');
    expect(created.request.body).toEqual(order);
    created.flush({ data: {} });
    service.listOwn().subscribe();
    expect(http.expectOne('/api/v1/online-orders').request.method).toBe('GET');
    service.listManagement().subscribe();
    expect(http.expectOne('/api/v1/online-orders/management').request.method).toBe('GET');
    service.managementOrder('00000000-0000-4000-8000-000000000003').subscribe();
    expect(http.expectOne('/api/v1/online-orders/management/00000000-0000-4000-8000-000000000003').request.method).toBe('GET');
    const proposal = { operationId: '00000000-0000-4000-8000-000000000004', reason: 'Existencias insuficientes para una línea.', deliveryMode: 'RECOJO' as const, coordinationPhone: '999 000 111', deliveryAddress: null, lines: [{ productId: '00000000-0000-4000-8000-000000000002', quantity: 1, unitPricePen: 14.5 }] };
    service.propose('00000000-0000-4000-8000-000000000003', proposal).subscribe();
    const proposed = http.expectOne('/api/v1/online-orders/management/00000000-0000-4000-8000-000000000003/proposals');
    expect(proposed.request.method).toBe('POST');
    expect(proposed.request.body).toEqual(proposal);
    proposed.flush({ data: {} });
    service.confirm('00000000-0000-4000-8000-000000000003').subscribe();
    const confirmation = http.expectOne('/api/v1/online-orders/management/00000000-0000-4000-8000-000000000003/confirmation');
    expect(confirmation.request.method).toBe('POST');
    expect(confirmation.request.body).toEqual({});
    confirmation.flush({ data: {} });
    const payment = { operationId: '00000000-0000-4000-8000-000000000007', paymentMethod: 'EFECTIVO' as const, declaredAmountPen: 14.5, reference: 'Recibo sintético' };
    service.recordPayment('00000000-0000-4000-8000-000000000003', payment).subscribe();
    const declaredPayment = http.expectOne('/api/v1/online-orders/management/00000000-0000-4000-8000-000000000003/payments');
    expect(declaredPayment.request.method).toBe('POST');
    expect(declaredPayment.request.body).toEqual(payment);
    declaredPayment.flush({ data: {} });
    const paymentDecision = { operationId: '00000000-0000-4000-8000-000000000008', decision: 'VALIDADO' as const, reason: null };
    service.decidePayment('00000000-0000-4000-8000-000000000003', '00000000-0000-4000-8000-000000000009', paymentDecision).subscribe();
    const decidedPayment = http.expectOne('/api/v1/online-orders/management/00000000-0000-4000-8000-000000000003/payments/00000000-0000-4000-8000-000000000009/decision');
    expect(decidedPayment.request.method).toBe('POST');
    expect(decidedPayment.request.body).toEqual(paymentDecision);
    decidedPayment.flush({ data: {} });
    const operation = { operationId: '00000000-0000-4000-8000-000000000010' };
    service.startPreparation('00000000-0000-4000-8000-000000000003', operation).subscribe();
    expect(http.expectOne('/api/v1/online-orders/management/00000000-0000-4000-8000-000000000003/preparation').request.method).toBe('POST');
    service.markReadyForPickup('00000000-0000-4000-8000-000000000003', operation).subscribe();
    expect(http.expectOne('/api/v1/online-orders/management/00000000-0000-4000-8000-000000000003/ready-for-pickup').request.method).toBe('POST');
    service.markDispatched('00000000-0000-4000-8000-000000000003', operation).subscribe();
    expect(http.expectOne('/api/v1/online-orders/management/00000000-0000-4000-8000-000000000003/dispatch').request.method).toBe('POST');
    const delivery = { operationId: '00000000-0000-4000-8000-000000000011', receiver: 'Cliente sintético', proofNote: null };
    service.completeDelivery('00000000-0000-4000-8000-000000000003', delivery).subscribe();
    const completed = http.expectOne('/api/v1/online-orders/management/00000000-0000-4000-8000-000000000003/delivery');
    expect(completed.request.method).toBe('POST');
    expect(completed.request.body).toEqual(delivery);
    completed.flush({ data: {} });
    const cancellation = { operationId: '00000000-0000-4000-8000-000000000012', reason: 'Cambio de plan sintético.' };
    service.cancelPending('00000000-0000-4000-8000-000000000003', cancellation).subscribe();
    expect(http.expectOne('/api/v1/online-orders/00000000-0000-4000-8000-000000000003/cancellation').request.body).toEqual(cancellation);
    service.requestCancellation('00000000-0000-4000-8000-000000000003', cancellation).subscribe();
    expect(http.expectOne('/api/v1/online-orders/00000000-0000-4000-8000-000000000003/cancellation-request').request.body).toEqual(cancellation);
    service.cancelPreDispatch('00000000-0000-4000-8000-000000000003', cancellation).subscribe();
    expect(http.expectOne('/api/v1/online-orders/management/00000000-0000-4000-8000-000000000003/cancellation').request.body).toEqual(cancellation);
    const cancellationDecision = { operationId: '00000000-0000-4000-8000-000000000013', decision: 'CANCELADA' as const, reason: 'Autorizada de forma sintética.' };
    service.decideCancellation('00000000-0000-4000-8000-000000000014', cancellationDecision).subscribe();
    expect(http.expectOne('/api/v1/online-orders/management/cancellations/00000000-0000-4000-8000-000000000014/decision').request.body).toEqual(cancellationDecision);
    const returned = { operationId: '00000000-0000-4000-8000-000000000015', reason: 'Producto sintético sin uso.', lines: [{ productId: '00000000-0000-4000-8000-000000000002', quantity: 1 }] };
    service.requestReturn('00000000-0000-4000-8000-000000000003', returned).subscribe();
    expect(http.expectOne('/api/v1/online-orders/00000000-0000-4000-8000-000000000003/returns').request.body).toEqual(returned);
    const returnDecision = { operationId: '00000000-0000-4000-8000-000000000016', decision: 'AUTORIZADA' as const, reason: null };
    service.decideReturn('00000000-0000-4000-8000-000000000017', returnDecision).subscribe();
    expect(http.expectOne('/api/v1/online-orders/management/returns/00000000-0000-4000-8000-000000000017/decision').request.body).toEqual(returnDecision);
    const receipt = { lines: [{ returnLineId: '00000000-0000-4000-8000-000000000018', receivedQuantity: 1 }] };
    service.receiveReturn('00000000-0000-4000-8000-000000000017', receipt).subscribe();
    expect(http.expectOne('/api/v1/online-orders/management/returns/00000000-0000-4000-8000-000000000017/receipt').request.body).toEqual(receipt);
    const inspection = { lines: [{ returnLineId: '00000000-0000-4000-8000-000000000018', restockedQuantity: 1 }] };
    service.inspectReturn('00000000-0000-4000-8000-000000000017', inspection).subscribe();
    expect(http.expectOne('/api/v1/online-orders/management/returns/00000000-0000-4000-8000-000000000017/inspection').request.body).toEqual(inspection);
    service.closeReturn('00000000-0000-4000-8000-000000000017').subscribe();
    expect(http.expectOne('/api/v1/online-orders/management/returns/00000000-0000-4000-8000-000000000017/closure').request.body).toEqual({});
    const decision = { operationId: '00000000-0000-4000-8000-000000000005', decision: 'ACEPTADA' as const };
    service.decideProposal('00000000-0000-4000-8000-000000000006', decision).subscribe();
    const decided = http.expectOne('/api/v1/online-orders/proposals/00000000-0000-4000-8000-000000000006/decision');
    expect(decided.request.method).toBe('POST');
    expect(decided.request.body).toEqual(decision);
    decided.flush({ data: {} });
    service.configuration().subscribe();
    expect(http.expectOne('/api/v1/online-orders/delivery-configuration').request.method).toBe('GET');
    const configuration = { pickupLocation: 'Recojo', deliveryEnabled: true, fixedDeliveryFeePen: 9.5, coverageDescription: 'Cobertura' };
    service.saveConfiguration(configuration).subscribe();
    const saved = http.expectOne('/api/v1/online-orders/delivery-configuration');
    expect(saved.request.method).toBe('PUT');
    expect(saved.request.body).toEqual(configuration);
    saved.flush({ data: configuration });
    http.verify();
  });
});
